const SPECIAL: Record<string, string> = { ı: 'I', İ: 'I', ß: 'SS', æ: 'AE', ø: 'O', œ: 'OE', đ: 'D', ł: 'L', '—': '-', '–': '-', '·': '-', '’': "'", '‘': "'", '“': '"', '”': '"' };

/**
 * Maps text onto the font: strips accents (ş -> S), uppercases, and turns runs
 * of anything the font can't draw (e.g. CJK) into a single "?".
 */
export function toPixelText(text: string): string {
  const mapped = [...text]
    .map((ch) => SPECIAL[ch] ?? ch)
    .join('')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase();
  return [...mapped].map((ch) => (PIXEL_GLYPHS[ch] ? ch : '\u0000')).join('').replace(/\u0000+/g, '?');
}

/** Path data for `text` drawn from (x, y) with square pixels of `size`; glyphs advance 6 pixels. */
export function pixelPath(text: string, x: number, y: number, size: number, dot = size): string {
  let d = '';
  [...text].forEach((ch, i) => {
    const glyph = PIXEL_GLYPHS[ch] ?? PIXEL_GLYPHS['?'];
    const left = x + i * 6 * size;
    glyph.forEach((row, r) => {
      for (let c = 0; c < 5; c++) {
        if (row[c] === '1') d += `M${left + c * size} ${y + r * size}h${dot}v${dot}h-${dot}z`;
      }
    });
  });
  return d;
}
